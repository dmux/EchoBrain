fn main() {
    // Tauri v2 gates *app* commands behind the ACL, not just plugin commands.
    // Without this, every `invoke()` from the frontend is rejected at runtime
    // with "not allowed. Plugin not found" — the app builds, launches and looks
    // fine, and then fails on the first search.
    //
    // Naming each command here autogenerates `allow-…`/`deny-…` permissions,
    // which `capabilities/default.json` then grants. Adding a command means
    // adding it in three places: here, `generate_handler!`, and the capability.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "search_memories",
            "capture_memory",
            "forget_memory",
            "library",
            // The same omission again, and the reason the test below now checks
            // `generate_handler!` against this list rather than only the other
            // way round: both were registered as commands and reachable from
            // the library view, and both would have been refused by the ACL.
            "list_memories",
            "update_memory",
            "dictation_available",
            "start_dictation",
            "stop_dictation",
            "audio_level",
            // Was missing until now, and worked only because a stale
            // `permissions/autogenerated/login_sso.toml` happened to survive on
            // disk. A clean checkout would have regenerated without it and the
            // button would fail at runtime with "Plugin not found" — the exact
            // failure the comment above warns about.
            "login_sso",
            "answering_available",
            "speech_available",
            "classify_intent",
            "ask_memories",
            "speak",
            "stop_speaking",
            "available_voices",
            "get_settings",
            "set_settings",
            "get_connection",
            "set_connection",
            "conversation_available",
            "start_conversation",
            "stop_conversation",
            // The same omission as `login_sso` above, one feature later.
            // `stop_and_measure_voice` was surviving on a stale autogenerated
            // toml; the other two had no permission at all, so enrolment could
            // never save — the ACL rejected `save_voice_profile` before it
            // reached any of the code that writes the profile.
            "get_voice_profile",
            "stop_and_measure_voice",
            "save_voice_profile",
        ]),
    ))
    .expect("tauri-build failed");
}
